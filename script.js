const metaDescription=document.querySelector('meta[name="description"]');

function detectLanguage(){
  const urlLang=new URLSearchParams(location.search).get('lang');
  if(urlLang==='ru'||urlLang==='ua') return urlLang;
  const saved=localStorage.getItem('shtorLang');
  if(saved==='ru'||saved==='ua') return saved;
  return navigator.language?.toLowerCase().startsWith('uk')?'ua':'ru';
}

function applyLanguage(lang,updateUrl=true){
  const t=translations[lang]||translations.ru;
  document.documentElement.lang=lang==='ua'?'uk':'ru';
  document.title=t.title;
  if(metaDescription) metaDescription.content=t.description;

  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key=el.dataset.i18n;
    if(t[key]!==undefined) el.textContent=t[key];
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el=>{
    const key=el.dataset.i18nHtml;
    if(t[key]!==undefined) el.innerHTML=t[key];
  });
  document.querySelectorAll('[data-i18n-alt]').forEach(el=>{
    const key=el.dataset.i18nAlt;
    if(t[key]!==undefined) el.alt=t[key];
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(el=>{
    const key=el.dataset.i18nAria;
    if(t[key]!==undefined) el.setAttribute('aria-label',t[key]);
  });
  document.querySelectorAll('.lang-btn').forEach(btn=>{
    const active=btn.dataset.lang===lang;
    btn.classList.toggle('is-active',active);
    btn.setAttribute('aria-pressed',String(active));
  });

  if(currentProjectId) updateGalleryInfo();
  localStorage.setItem('shtorLang',lang);
  if(updateUrl){
    const url=new URL(location.href);
    url.searchParams.set('lang',lang);
    history.replaceState({},'',url);
  }
}

