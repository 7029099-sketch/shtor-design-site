let currentProjectId=null;
let currentGalleryIndex=0;
const viewer=document.getElementById('projectViewer');
const viewerMain=viewer?.querySelector('[data-gallery-main]');
const viewerThumbs=viewer?.querySelector('[data-gallery-thumbs]');
const viewerCurrent=viewer?.querySelector('[data-gallery-current]');
const viewerTotal=viewer?.querySelector('[data-gallery-total]');
const viewerName=viewer?.querySelector('[data-gallery-name]');
const viewerDescription=viewer?.querySelector('[data-gallery-description]');
const viewerFabric=viewer?.querySelector('[data-gallery-fabric]');
const viewerPalette=viewer?.querySelector('[data-gallery-palette]');
const viewerType=viewer?.querySelector('[data-gallery-type]');
const galleryStage=viewer?.querySelector('.gallery-stage');

function galleryLanguage(){return document.documentElement.lang==='uk'?'ua':'ru';}

function updateGalleryInfo(){
  if(!currentProjectId||!viewer) return;
  const p=projectGalleries[currentProjectId];
  const info=p[galleryLanguage()];
  viewerName.textContent=info.name;
  viewerDescription.textContent=info.description;
  viewerFabric.textContent=info.fabric;
  viewerPalette.textContent=info.palette;
  viewerType.textContent=info.type;
}

function setGalleryImage(index){
  if(!currentProjectId||!viewer) return;
  const p=projectGalleries[currentProjectId];
  currentGalleryIndex=(index+p.images.length)%p.images.length;
  viewerMain.src=p.images[currentGalleryIndex];
  viewerMain.alt=(p[galleryLanguage()].name)+' — '+(currentGalleryIndex+1);
  viewerCurrent.textContent=String(currentGalleryIndex+1);
  viewerTotal.textContent=String(p.images.length);
  viewerThumbs.querySelectorAll('.gallery-thumb').forEach((thumb,i)=>thumb.classList.toggle('is-active',i===currentGalleryIndex));
  galleryStage?.classList.remove('is-zoomed');
}

function openProject(projectId){
  const p=projectGalleries[projectId];
  if(!p||!viewer) return;
  currentProjectId=projectId;
  currentGalleryIndex=0;
  viewer.hidden=false;
  document.body.classList.add('gallery-open');
  viewerThumbs.innerHTML='';
  p.images.forEach((src,i)=>{
    const b=document.createElement('button');
    b.type='button';
    b.className='gallery-thumb'+(i===0?' is-active':'');
    b.setAttribute('aria-label',(i+1).toString());
    b.innerHTML='<img src="'+src+'" alt="">';
    b.addEventListener('click',()=>setGalleryImage(i));
    viewerThumbs.appendChild(b);
  });
  updateGalleryInfo();
  setGalleryImage(0);
}

function closeProject(){
  if(!viewer) return;
  viewer.hidden=true;
  document.body.classList.remove('gallery-open');
  galleryStage?.classList.remove('is-zoomed');
}

document.querySelectorAll('[data-project]').forEach(card=>card.addEventListener('click',()=>openProject(card.dataset.project)));
viewer?.querySelectorAll('[data-gallery-close]').forEach(el=>el.addEventListener('click',closeProject));
viewer?.querySelector('[data-gallery-prev]')?.addEventListener('click',()=>setGalleryImage(currentGalleryIndex-1));
viewer?.querySelector('[data-gallery-next]')?.addEventListener('click',()=>setGalleryImage(currentGalleryIndex+1));
viewer?.querySelector('[data-gallery-zoom]')?.addEventListener('click',()=>galleryStage?.classList.toggle('is-zoomed'));
document.addEventListener('keydown',e=>{
  if(!viewer||viewer.hidden) return;
  if(e.key==='Escape') closeProject();
  if(e.key==='ArrowLeft') setGalleryImage(currentGalleryIndex-1);
  if(e.key==='ArrowRight') setGalleryImage(currentGalleryIndex+1);
});
